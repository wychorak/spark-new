// Builds src/i18n/catalog.ts from scripts/i18n/translations.json.
//   node scripts/i18n-build.cjs                       regenerate the catalog
//   node scripts/i18n-build.cjs --import <src.json> <lang>=<file.tsv> ...
//        merge "id<TAB>text" files (ids index into <src.json>) into translations.json first
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const languages = ["en", "de", "uk", "es"];
const store = path.join(root, "scripts", "i18n", "translations.json");
const translations = fs.existsSync(store) ? JSON.parse(fs.readFileSync(store, "utf8")) : {};

const placeholderSet = (text) => new Set(text.match(/\{\d+\}/g) ?? []);
// A translation may drop a placeholder (e.g. a Polish plural suffix) but never invent one.
const placeholdersOk = (source, text) => [...placeholderSet(text)].every((item) => placeholderSet(source).has(item));
const problems = [];

const args = process.argv.slice(2);
if (args[0] === "--import") {
  const source = JSON.parse(fs.readFileSync(args[1], "utf8"));
  for (const spec of args.slice(2)) {
    const [language, file] = spec.split("=");
    if (!languages.includes(language)) throw new Error("Unknown language " + language);
    const lines = fs.readFileSync(file, "utf8").split(/\r?\n/).filter((line) => line.trim() && !line.startsWith("#"));
    for (const line of lines) {
      const tab = line.indexOf("\t");
      if (tab < 0) { problems.push(`${language}: no tab in "${line}"`); continue; }
      const id = Number(line.slice(0, tab));
      const text = line.slice(tab + 1).replace(/\\n/g, "\n");
      const key = source[id];
      if (key === undefined) { problems.push(`${language}: unknown id ${id}`); continue; }
      if (!placeholdersOk(key, text)) { problems.push(`${language} ${id}: placeholders differ: "${key}" -> "${text}"`); continue; }
      translations[key] = { ...(translations[key] ?? {}), [language]: text };
    }
  }
  const sorted = Object.fromEntries(Object.keys(translations).sort((a, b) => a.localeCompare(b, "pl")).map((key) => [key, translations[key]]));
  fs.writeFileSync(store, JSON.stringify(sorted, null, 1) + "\n");
}

const rows = Object.keys(translations)
  .sort((a, b) => a.localeCompare(b, "pl"))
  .map((key) => `  ${JSON.stringify(key)}: [${languages.map((language) => translations[key][language] === undefined ? "null" : JSON.stringify(translations[key][language])).join(", ")}]`);
const output = `// Generated by scripts/i18n-build.cjs from scripts/i18n/translations.json. Do not edit by hand.
export const catalogLanguages = ${JSON.stringify(languages)} as const;

export const catalog: Record<string, ReadonlyArray<string | null>> = {
${rows.join(",\n")}
};
`;
fs.writeFileSync(path.join(root, "src", "i18n", "catalog.ts"), output);
const counts = Object.fromEntries(languages.map((language) => [language, Object.values(translations).filter((row) => row[language] !== undefined).length]));
console.log("catalog entries:", rows.length, counts);
if (problems.length) {
  console.error(problems.join("\n"));
  process.exitCode = 1;
}
